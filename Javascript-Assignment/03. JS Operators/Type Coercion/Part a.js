// Q1) Convert the string `"25"` into a number using `Number()` and add `10` to it. Print the result.

```js
let val = "25"
val = Number(val)
console.log(val+10) 
```

// Q2) Convert the number `100` into a string using `String()` and join it with `" rupees"`. Print the result.

```js
let num = 100;
num = String(num);
console.log(num+" rupees")
```

// Q3) Convert the value `0` into a boolean using `Boolean()` and print it.

```js
let val = 0;
val = Boolean(val)
console.log(val)
```

